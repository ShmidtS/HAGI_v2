def _weights_block(weights: dict[str, float]) -> str:
    return "\n".join(f"      {k}: {v}" for k, v in weights.items())


def write_generation(
    gen: int,
    root_ckpt: str,
    seed_base: int,
    rank: int = 64,
    domains: list[str] | None = None,
    out_dir: Path | None = None,
) -> dict[str, Path]:
    """Materialize gen-N configs under ``checkpoints/gen<N>/configs/``.

    ``seed_base``: the seed family (e.g. 23 -> seeds 231xx). Advance it
    (24, 25, ...) on every retry of the same generation.
    """
    domains = domains or DOMAINS
    out = out_dir or (ROOT / f"checkpoints/gen{gen}/configs")
    out.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for d in domains:
        c = _DOMAIN[d]
        tau_line = (
            f"    inverse_sqrt_tau: {c['tau']}\n" if c["tau"] else ""
        )
        s = LEAF_TEMPLATE.format(
            comment="Latent-line leaf", domain=d, gen=gen,
            init_seed=seed_base * 1000 + c["init_off"],
            z_loss=c["z_loss"], scale=c["scale"], rank=rank,
            root_ckpt=root_ckpt, max_steps=c["max_steps"], lr=c["lr"],
            tau_line=tau_line,
            leaf_dir=f"checkpoints/gen{gen}_leaf_{d}",
            data_seed=seed_base * 1000 + c["data_off"],
            weights_block=_weights_block(c["weights"]),
        )
        p = out / f"leaf_{d}.yaml"
        p.write_text(s, encoding="utf-8")
        paths[f"leaf_{d}"] = p
    # root_ft: the ladder's ACTUAL historical mix (Map≠Territory: taken
    # from the derive-chain, not from mix.json).
    root_mix = {
        "edu": 0.2, "slimpajama": 0.15, "openwebmath": 0.25,
        "oscar_ru": 0.1, "wikipedia_ru": 0.1, "python_instruct": 0.2,
    }
    s = ROOT_FT_TEMPLATE.format(
        gen=gen, rank=rank,
        root_ckpt=f"checkpoints/gen{gen}_root/root.pt",
        ft_dir=f"checkpoints/gen{gen}_root_ft",
        data_seed=15111,  # pinned: the ladder's common eval/train seed
        weights_block=_weights_block(root_mix),
    )
    p = out / "root_ft.yaml"
    p.write_text(s, encoding="utf-8")
    paths["root_ft"] = p
    return paths


