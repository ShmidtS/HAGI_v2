"""SSOT generation-config builder — one template, per-domain overrides.

Replaces the configs/gen<N>_leaf_<d>.yaml proliferation (185 files):
every generation's configs are DERIVED here and written into that
generation's own checkpoint directory
(``checkpoints/gen<N>/configs/``), never into ``configs/``.

Design (KISS / DRY):
- ``LEAF_TEMPLATE`` — the single leaf YAML (geometry, optimizer,
  guards). Only the values that genuinely differ per domain live in
  ``DOMAINS``.
- ``DOMAINS`` — per-domain overrides: data mix, head regularization,
  step budget, data-seed offsets. These are the measured winning-line
  values (gen-18..gen-40 lineage); change them HERE, nowhere else.
- ``write_generation(gen, root_ckpt, seed_base)`` — materializes
  ``leaf_<d>.yaml`` (6 domains) + ``root_ft.yaml`` into
  ``checkpoints/gen<N>/configs/`` and returns the paths.

Seed scheme: ``seed_base`` is the two-digit generation seed family
(23 -> 231xx). ``init``-seeds differ per domain (R66 same-origin sibs:
distinct seeds, shared prior); data-seeds follow the historical
per-domain offsets. ``seed_base`` must advance on every RETRY of the
same generation (fresh-data injection, R104 stop_condition).
"""
