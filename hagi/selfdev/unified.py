    def learn_text(  # проглотить текст как домен `name`
        self, name: str, text: str, epochs: int = 200, repeat: int = 2  # аргументы как у ingest
    ) -> dict:  # возвращает итог ingest
        d = CKPT_DIR / "domains"  # каталог доменов
        d.mkdir(parents=True, exist_ok=True)  # создать, если нет
        (d / f"{name}.bin").write_text(text, encoding="utf-8")  # сохранить текст в <name>.bin в utf-8
        return self.ingest(name, text.encode("utf-8"), epochs=epochs, repeat=repeat)  # ingest байтов текста

    # ---- вывод ----

    def ask(self, prompt: str, n: int = 400,  # ответ на prompt: до n новых байтов
            domain: str | None = None) -> str:  # домен, чей адаптер может примениться
        with self._DomainScope(self, domain):  # с адаптером домена, прошедшим живой гейт
            r = self.model.generate(prompt, n_bytes=n)  # r = prompt + сгенерированные байты
        return r[len(prompt) :].strip() if r.startswith(prompt) else r  # срезать prompt и обрезать пробелы; иначе вернуть r целиком

    def ask_auto(self, prompt: str, max_bytes: int = 4096,  # ответ длиной, которую выбирает сама модель
                 domain: str | None = None) -> str:  # домен для адаптера
        """Модель читает ВЕСЬ prompt (окна покрытия) и сама решает, каким
        длинным будет ответ (генерация с самозавершением). `domain`: адаптер
        домена применяется, только если он проходит живой парный гейт."""
        with self._DomainScope(self, domain):  # с адаптером домена
            r = self.model.generate_auto(prompt, max_bytes=max_bytes)  # r = prompt + ответ не длиннее max_bytes
        return r[len(prompt):].strip() if r.startswith(prompt) else r  # срезать prompt и обрезать пробелы; иначе вернуть r целиком
    # ---- консолидация знаний из внешней памяти ----

    def memory(self):
        """Синглтон SemanticMemory (SQLite + FTS5 + архив gemma)."""
        from hagi.memory_store import SemanticMemory  # импорт класса памяти
        import hagi.base.util as _u  # утилиты с путём CKPT_DIR
        if getattr(self, "_mem", None) is None:  # память ещё не создана
            self._mem = SemanticMemory(str(_u.CKPT_DIR / "memory.db"))  # создать её в файле memory.db
        return self._mem  # вернуть синглтон

    def remember(self, text: str) -> None:
        """Сохранить разговор или факт насовсем (веса не меняются)."""
        self.memory().add(text)  # добавить текст в память

    def consolidate(self, query: str, n_bytes: int = 600) -> str:
        """Ответ с опорой на память: найденные страницы памяти ставятся
        перед запросом в prompt, затем обычная генерация `ask`."""
        hits = self.memory().query(query, top_k=3)  # до 3 самых подходящих записей (оценка, id, текст)
        sep = chr(10)  # разделитель строк: перевод строки
        evidence = sep.join(t for _c, _pid, t in hits) if hits else ""  # тексты находок через перевод строки; пусто, если находок нет
        prompt = (evidence + sep + sep + query) if evidence else query  # prompt = находки + 2 перевода строки + запрос; иначе сам запрос
        return self.ask(prompt, n=n_bytes)  # ответ на собранный prompt

    def learn_from_dialog(self, dialog_text: str,  # выучить диалог
                          name: str | None = None) -> dict:  # имя домена (None — авто)
        """Полный цикл консолидации: диалог -> постоянная память ->
        ingest как обучающий домен (модель УЧИТСЯ на нём)."""
        name = name or ("dialog_"  # имя по умолчанию "dialog_" + ...
                        + time.strftime("%Y%m%d_%H%M%S"))  # ... дата и время ГГГГММДД_ЧЧММСС
        self.remember(dialog_text)  # сохранить диалог в памяти
        return self.ingest(name, dialog_text.encode("utf-8"),  # проглотить байты диалога в utf-8 ...
                           epochs=1, repeat=1)  # ... одна эпоха, один повтор

