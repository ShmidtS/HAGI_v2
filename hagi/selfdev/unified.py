    def to_symbolic(self) -> dict:
        """Трёхзначная проекция первого слоя ствола на подложку ткани.
            Итоговый артефакт символьный: маска из {−1, 0, +1} и масштаб,
            W ≈ mask·scale, где scale = 2·mean|W1| + 10^−12."""
        import torch  # импорт torch

        W1 = self.model.W1.detach()  # первая матрица весов без градиентов
        scale = W1.abs().mean() * 2 + 1e-12  # scale = 2·mean|W1| + 10^−12 (средний модуль веса, удвоенный)
        tern = torch.round(W1 / scale).clamp(-1, 1).int()  # tern = clip(round(W1/scale), −1, 1) — элементы {−1, 0, +1}
        # Возвращается сама НАГРУЗКА (маска + масштаб), а не только статистика:
        # символьный артефакт должен быть восстановим.
        return {  # вернуть словарь описания
            "shape": list(W1.shape),  # форма матрицы W1
            "scale": scale.item(),  # масштаб как число
            "ternary_nonzeros": int((tern != 0).sum()),  # число ненулевых элементов маски
            "density": round(float((tern != 0).float().mean()), 4),  # плотность = доля ненулевых, 4 знака
            "payload": {  # вложенный словарь нагрузки
                "mask": tern.tolist(),          # элементы {−1,0,+1} по весам
                "scale": scale.item(),  # масштаб (общий скаляр матрицы)
                "schema": "W ~ mask * scale (per-matrix scalar scale)",  # строка-описание схемы квантования (текст не переводится)
            },
        }

