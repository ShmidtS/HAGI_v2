    def save(self) -> None:  # сохранить модель и книгу доменов
        import torch as _t  # локальный импорт torch

        # Тензоры именуются самой моделью (Rope хранит прежние имена
        # emb,q,W1,b1,W2,b2 + blk{i}.*; у HNet свой набор)
        st = {n: p_.detach().cpu() for n, p_ in zip(self.model.param_names(), self.model.params())}  # словарь имя -> копия тензора на CPU
        # Блоки внимания, сохраняющие функцию
        if getattr(self.model, "ARCH", "rope") == "rope":  # архитектура rope (по умолчанию rope)
            st["blocks"] = [  # список блоков ...
                {k: v.detach().cpu() for k, v in blk.items()}  # ... словарь имя -> тензор на CPU
                for blk in getattr(self.model, "blocks", [])]  # ... по всем блокам модели
        st.update(  # добавить:
            {"k": self.model.k, "dim": self.model.dim, "hidden": self.model.hidden}  # длину контекста, dim и hidden
        )
        st["arch"] = getattr(self.model, "ARCH", "rope")  # имя архитектуры (по умолчанию rope)
        if hasattr(self.model, "bypass_t5"):  # у модели есть точный обход
            st["bypass"] = {"boost": self.model.bypass_boost,  # прибавка к логиту
                            "t5": [[k.hex(), v[0], v[1], v[2]] for k, v in self.model.bypass_t5.items()],  # 5-байтовый словарь: ключ в hex, предсказание, счёт, сбой
                            "t3": [[k.hex(), v[0], v[1], v[2]] for k, v in self.model.bypass_t3.items()]}  # 3-байтовый словарь
        st["spike_k"] = getattr(self.model, "spike_k", None)  # порог спайкинга (None — выключен): режим переживает перезапуск
        st["frozen_blocks"] = sorted(getattr(self.model, "frozen_blocks", ()))  # номера замороженных блоков по возрастанию
        if getattr(self, "fibers", None):  # волокна доменов
            st["fibers"] = {dom: {n: p_.detach().cpu() for n, p_ in fib.__dict__.items() if isinstance(p_, _t.nn.Parameter)} for dom, fib in self.fibers.items()}  # домен -> параметры волокна
        gpm = getattr(self.model, "gpm_left", None)  # базисы GPM (причинная модель)
        if gpm:  # есть
            st["gpm_left"] = {n: U.detach().cpu() for n, U in gpm.items()}  # имя параметра -> базис (столбцы)
        gpm_r = getattr(self.model, "gpm_right", None)  # правые базисы GPM (softmax-голова emb)
        if gpm_r:  # есть
            st["gpm_right"] = {n: U.detach().cpu() for n, U in gpm_r.items()}  # имя параметра -> базис
        # Сохранить геометрию внимания (theta0/lam): без них load() молча
        # вернёт значения по умолчанию, и обученный профиль свежести
        # изменится после перезапуска.
        for g in ("theta0", "lam"):  # по именам атрибутов
            if hasattr(self.model, g):  # атрибут есть
                st[g] = float(getattr(self.model, g))  # сохранить как число
        # Обученные адаптеры раньше не сохранялись — каждый перезапуск молча
        # возвращал их к тождеству B=0. Хранить A/B по каждому домену.
        bank = getattr(self, "adapter_bank", None)  # банк адаптеров
        if bank is not None:  # банк есть
            st["adapter_bank"] = {  # домен -> веса адаптера ...
                dom: {"A": ad.A, "B": ad.B}  # ... A и B адаптера
                for dom, ad in bank._adapters.items()}  # ... по всем адаптерам банка
        # Сохранить реестр законов — законы переживают перезапуск.
        reg = getattr(self, "law_registry", None)  # реестр законов
        if reg:  # он не пуст
            st["law_registry"] = {  # домен -> список записей ...
                dom: [{"feature": e["feature"],  # имя признака ...
                       "verify": e["verify"],  # ... статус проверки ...
                       "support": e.get("support"),  # ... носитель ...
                       # параметр характеристики целиком: реестр хранит и не аффинные законы
                       "q_param": repr(e["bp"].q_param),  # ... параметр q_param в виде текста Python ...
                       "basis": e["bp"].basis,  # ... базис ...
                       "payload": e["bp"].payload,  # ... полезная нагрузка ...
                       "accepted_to_registry": e.get(  # ... принят ли в реестр ...
                           "accepted_to_registry", True),  # ... (по умолчанию True) ...
                       "commit_id": e.get("commit_id"),  # ... идентификатор фиксации ...
                       "shift": e.get("shift"),  # ... сдвиг ...
                       "n_shifts": e.get("n_shifts"),  # ... число сдвигов ...
                       "evidence": e.get("evidence", [])}  # ... список свидетельств (по умолчанию пуст)
                      for e in v]  # по записям домена
                for dom, v in reg.items()}  # по доменам реестра
        _guard_prod_write()  # проверить, что запись в рабочий каталог разрешена
        _unified_pt().parent.mkdir(parents=True, exist_ok=True)  # создать каталог файла модели
        # Атомарная запись состояния: сбой посреди сохранения не должен
        # оставить обрезанный .pt или наполовину записанную книгу.
        import os as _os  # локальный импорт os
        tmp = _unified_pt().with_suffix(".pt.tmp")  # временный файл <имя>.pt.tmp
        _t.save(st, tmp)  # сохранить состояние во временный файл
        _os.replace(tmp, _unified_pt())  # атомарно заменить файл модели
        tmp_l = _ledger_js().with_suffix(".json.tmp")  # временный файл книги <имя>.json.tmp
        tmp_l.write_text(  # записать книгу доменов ...
            json.dumps(self.domains, ensure_ascii=False, indent=1),  # ... как JSON с отступом 1, неанглийские буквы как есть
            encoding="utf-8")  # ... в utf-8
        _os.replace(tmp_l, _ledger_js())  # атомарно заменить файл книги

