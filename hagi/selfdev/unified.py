#!/usr/bin/env python3
"""HAGI Unified — единая самообучающаяся нейро-символьная модель.

ОДНА модель. Принимает ЛЮБЫЕ данные (байты). Растёт эксперт за экспертом.
Самоэволюция: ingest -> сертифицированное обучение -> квантование в символы
-> вплетение в ткань; процессор и есть модель.

Устройство:
  - ОДНО тело (RopeAttentionByteLM, контекст k=96) обучается на всём увиденном;
    отдельных контрольных точек под задачи нет.
  - Домены учитываются в книге доменов (имя -> байты, CE), поэтому забывание
    измеряется по каждому домену после каждого ingest.
  - Нейро -> символическое: обученные адаптеры квантуются в тернарные маски;
    закрепляемый артефакт символический.

Контракт ingest: ЛЮБОЙ файл — текст, двоичный, CSV, JSON (hagi.ingest
обрабатывает структурированные; сырые байты работают всегда).

Формулы:
  окно контекста для позиции p: X = idx[p−n .. p−1], n = min(k, p), старые
  байты первыми; цель y = idx[p + k];
  адаптер: h' = h + (h @ A^T) @ B^T, при B = 0 — тождество;
  парный выигрыш: d_i = CE_до,i − CE_после,i; нижняя граница = mean(d) − 2.4·SE;
  допуск по эмпирическому Бернштейну: eps = sqrt(2·sig2·L/n) + 2·b·L/n,
  L = ln(2·n_states/0.05), b = max|d|; принять, если mean(d) > eps;
  сигнал роста: 128·G2 / (2·L), G2 = сумма квадратов градиентов, L = потери.
"""
