    def evolve_step(  # один цикл по всем доменам
        self, sources: list[tuple[str, bytes]] | None = None, epochs: int = 120  # новые источники (имя, байты) и число эпох
    ) -> dict:  # итог: число доменов, CE по доменам, символьная проекция
        """Один цикл по всем доменам (+ новые `sources`): ingest каждого,
        затем замер забывания — CE на случайной выборке окон каждого домена
        (до 256 окон, зерно 9) — и трёхзначная символьная проекция ствола."""
        if sources:  # есть новые источники
            for name, data in sources:  # по (имя, байты)
                (CKPT_DIR / "domains").mkdir(exist_ok=True, parents=True)  # создать каталог доменов
                (CKPT_DIR / "domains" / f"{name}.bin").write_bytes(data)  # сохранить байты источника
                self.ingest(name, data, epochs=epochs)  # проглотить источник
        report = self.ingest("__evolve__", b"", epochs=epochs) if False else None  # всегда None: ветка ingest выключена (условие False)
        # CE на отложенных окнах каждого домена (мера забывания)
        ce_by = {}  # домен -> CE
        for name in self.domains:  # по всем доменам книги
            data = self._domain_bytes(name, self.domains[name])  # байты домена
            if not data:  # пусто
                continue  # пропустить
            idx = (  # байты в целые индексы ...
                np.frombuffer(data, dtype=np.uint8).astype(np.int64)  # ... через numpy ...
                if (np := __import__("numpy"))  # ... импортируя numpy в локальное имя np (истинно) ...
                else None  # ... иначе None (недостижимо)
            )
            if len(idx) < self.k + 32:  # короче k + 32
                continue  # пропустить
            rng = np.random.default_rng(9)  # генератор, зерно 9
            n = len(idx) - self.k  # число начал окон: n = len − k
            sel = rng.choice(n, min(256, n), replace=False)  # до 256 различных начал
            X = np.stack([idx[i : i + self.k] for i in sel])  # окна X_i = idx[i..i+k−1]
            yv = idx[sel + self.k]  # ответы yv_i = idx[i + k]
            t = self.model.t  # torch: ссылка на библиотеку
            ctx = t.as_tensor(X, dtype=t.long)  # окна как тензор
            nxt = t.as_tensor(yv, dtype=t.long)  # ответы как тензор
            with t.no_grad():  # без градиентов
                ce = float(t.nn.functional.cross_entropy(self.model.logits(ctx), nxt))  # ce = средняя CE(logit(X), yv)
            ce_by[name] = round(ce, 4)  # записать CE домена с 4 знаками
        sym = self.to_symbolic()  # символьная проекция ствола
        return {"domains": len(self.domains), "ce_by_domain": ce_by, "symbolic": sym}  # итог: число доменов, CE по доменам, проекция
