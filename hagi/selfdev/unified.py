import hashlib  # хеш sha1 — отпечаток байтов домена
import json  # чтение и запись книги доменов
import time  # отметка времени и замер длительности ingest

import numpy as np  # численные массивы
from pathlib import Path  # пути к файлам
from typing import Any  # тип значений словаря доменов

