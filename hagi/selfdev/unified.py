    @classmethod  # метод класса
    def load(cls) -> "Unified":  # загрузить Unified из файла модели
        import torch as _t  # локальный импорт torch
        from hagi.models import lm as lm_mod  # модуль создания моделей

        u = cls.__new__(cls)  # создать объект без вызова __init__
        u.lm_mod = lm_mod  # запомнить модуль моделей
        st = _t.load(_unified_pt(), weights_only=False)  # прочитать сохранённый словарь
        u.k, u.dim, u.hidden = st["k"], st["dim"], st["hidden"]  # длина контекста, dim, hidden
        u.model = lm_mod.make_lm(st.get("arch", "rope"), u.dim, u.hidden,  # создать модель архитектуры st["arch"] (по умолчанию rope) ...
                                 theta0=st.get("theta0", 1.0), lam=st.get("lam", 0.05))  # ... с theta0 (по умолчанию 1.0) и lam (по умолчанию 0.05)
        if "adapter_bank" in st:  # в состоянии есть адаптеры
            from hagi.base.trunk_ops import AdapterBank  # класс банка адаптеров
            bank = u.adapter_bank = AdapterBank(  # создать банк ранга 2 размерности ...
                d=getattr(u.model, "adapter_dim", u.model.hidden), r=2)  # ... adapter_dim (если есть) иначе hidden
            for dom, ab in st["adapter_bank"].items():  # по доменам и их весам
                ad = bank.get(dom)  # адаптер домена (свежий или сохранённый)
                ad.r = _t.as_tensor(ab["A"]).shape[0]  # ранг = число строк A (ранг бывает разный)
                ad.A = _t.as_tensor(ab["A"])  # веса A
                ad.B = _t.as_tensor(ab["B"])  # веса B
        if "law_registry" in st:  # в состоянии есть реестр законов
            import numpy as _np  # локальный импорт numpy
            from hagi.invent.invention_multi import feature_fn  # сборка функции характеристики по (имя, параметр)
            import ast as _ast  # разбор текста Python (параметр характеристики)
            from hagi.invent.invention import ConstructBlueprint  # класс чертежа конструкции
            u.law_registry = {}  # пустой реестр
            for dom, laws in st["law_registry"].items():  # по доменам и спискам записей
                entries = []  # восстановленные записи домена
                for e in laws:  # по сохранённым записям
                    # старые состояния хранили только аффинные законы двумя полями coefs/bias
                    q_param = (_ast.literal_eval(e["q_param"]) if "q_param" in e  # параметр из текста, если он сохранён ...
                               else (tuple(e["coefs"]), e["bias"]))  # ... иначе (коэффициенты, смещение) старого формата
                    ffn = feature_fn(e["feature"], q_param)  # функция характеристики ffn(x) — та же, что при синтезе
                    bp = ConstructBlueprint(  # чертёж: признак, параметры, функция, базис, нагрузка, 9
                        e["feature"], q_param,  # аргументы чертежа: признак, его параметр
                        ffn, e["basis"], e["payload"], 9)  # продолжение: функция, базис, нагрузка, число 9
                    entries.append({"feature": e["feature"],  # запись: признак ...
                                    "bp": bp,  # ... чертёж ...
                                    "verify": e["verify"],  # ... статус проверки ...
                                    "support": e.get("support"),  # ... носитель ...
                                    "accepted_to_registry": e.get(  # ... принят ли в реестр (по умолчанию True) ...
                                        "accepted_to_registry", True),  # ключ «принят в реестр», значение по умолчанию True
                                    "commit_id": e.get("commit_id"),  # ... идентификатор фиксации ...
                                    "shift": e.get("shift"),  # ... сдвиг ...
                                    "n_shifts": e.get("n_shifts"),  # ... число сдвигов ...
                                    "evidence": e.get("evidence", [])})  # ... свидетельства (по умолчанию пусто)
                if entries:  # есть хоть одна запись
                    u.law_registry[dom] = entries  # добавить домен в реестр
        with _t.no_grad():  # без градиентов
            for n, p_ in zip(u.model.param_names(), u.model.params()):  # по именам и параметрам модели
                if n in st:  # параметр сохранён
                    p_.copy_(st[n].to(p_.device))  # скопировать значение на устройство параметра
        if "fibers" in st:  # восстановить волокна
            from hagi.models.optimal_lm import CortexFiber  # класс волокна
            u.fibers = {}  # банк
            for dom, pars in st["fibers"].items():  # по доменам
                fib = CortexFiber.__new__(CortexFiber)  # без конструктора
                for n, v in pars.items(): setattr(fib, n, _t.nn.Parameter(_t.as_tensor(v)))  # параметры
                u.fibers[dom] = fib  # добавить
        if "gpm_left" in st:  # восстановить базисы GPM
            u.model.gpm_left = {n: _t.as_tensor(U) for n, U in st["gpm_left"].items()}  # имя -> базис
        if "gpm_right" in st:  # правые базисы
            u.model.gpm_right = {n: _t.as_tensor(U) for n, U in st["gpm_right"].items()}  # имя -> базис
        # Старые состояния rope хранят выращенные блоки отдельно
        for blk in st.get("blocks", []) or []:  # по сохранённым блокам (по умолчанию пусто)
            u.model.grow()  # добавить блок-тождество
            live = u.model.blocks[-1]  # живой блок модели
            with _t.no_grad():  # без градиентов
                for k in live:  # по тензорам блока
                    live[k].copy_(blk[k].to(live[k].device))  # скопировать тензор сохранённого блока
        if "spike_k" in st:  # в состоянии сохранён режим спайкинга
            u.model.spike_k = st["spike_k"]  # восстановить порог спайкинга
        if "bypass" in st and hasattr(u.model, "bypass_t5"):  # в состоянии сохранён точный обход
            u.model.bypass_boost = st["bypass"]["boost"]  # прибавка
            u.model.bypass_t5 = {bytes.fromhex(k): [p, c, b] for k, p, c, b in st["bypass"]["t5"]}  # восстановить 5-байтовый словарь
            u.model.bypass_t3 = {bytes.fromhex(k): [p, c, b] for k, p, c, b in st["bypass"]["t3"]}  # и 3-байтовый  # восстановить его
        u.model.frozen_blocks = set(st.get("frozen_blocks", []))  # замороженные блоки: множество номеров (по умолчанию пустое)
        u.domains = (  # книга доменов ...
            json.loads(_ledger_js().read_text(encoding="utf-8")) if _ledger_js().exists() else {}  # ... из JSON-файла в utf-8, иначе пустой словарь
        )
        return u  # вернуть загруженный объект

    def predict_next_byte(self, context: bytes | str,  # предсказать следующий байт контекста
                          prefer_domain: str | None = None,  # домен, чьи законы проверяются первыми (None — все)
                          allow_neural: bool = False) -> dict:  # разрешить нейронную догадку без закона
        """Честное по умолчанию предсказание СЛЕДУЮЩЕГО байта невиданного контекста.

            Приоритет:
              1. ДОКАЗАННЫЕ законы (verify == "PROVEN_EXACT") — заверенный ответ.
              2. Законы на удержании HOLD (частичный охват / проверка не
                 завершена) — прогноз закона возвращается с certified: False,
                 статус HOLD.
              3. Закон не подошёл -> статус HOLD, byte=None (без догадок).
            Нейронная модель по умолчанию НЕ спрашивается: незаверенная догадка
            выдавала бы себя за знание. Явное allow_neural=True разрешает
            догадку (статус NEURAL_GUESS, certified: False)."""
        import torch as _t  # локальный импорт torch
        if isinstance(context, str):  # контекст — строка
            context = context.encode("utf-8")  # перевести в байты utf-8
        registry = getattr(self, "law_registry", {}) or {}  # реестр законов (по умолчанию пуст)
        domains = ([prefer_domain] if prefer_domain  # только указанный домен, если он задан, ...
                   else list(registry.keys()))  # ... иначе все домены реестра
        ctx = (tuple(int(b) for b in context[-4:])  # последние 4 байта контекста как кортеж ...
               if len(context) >= 4  # ... если их не меньше 4 ...
               else tuple(int(b) for b in context))  # ... иначе весь контекст
        proven, hold = [], []  # списки доказанных и удерживаемых законов
        for dom in domains:  # по доменам
            for entry in registry.get(dom, []):  # по записям домена
                tgt = (proven if entry.get("verify") == "PROVEN_EXACT"  # доказанные идут в proven ...
                       else hold)  # ... все прочие в hold
                tgt.append((dom, entry))  # добавить пару (домен, запись)
        # 1) сначала доказанные законы
        for dom, entry in proven:  # по доказанным
            try:  # применение закона может завершиться ошибкой
                b = int(entry["bp"].apply(ctx)) % 256  # предсказанный байт: b = apply(ctx) mod 256
                return {"byte": b, "status": "OK",  # заверенный ответ: байт, статус OK ...
                        "source": f"law:{dom}:{entry['feature']}",  # ... источник — домен и признак закона ...
                        "certified": True}  # ответ заверен: ... certified = True
            except Exception:  # закон неприменим
                continue  # попробовать следующий
        # 2) законы HOLD — лучшая структурированная догадка
        for dom, entry in hold:  # по удерживаемым
            try:  # применение может завершиться ошибкой
                b = int(entry["bp"].apply(ctx)) % 256  # предсказанный байт: b = apply(ctx) mod 256
                return {"byte": b, "status": "HOLD",  # прогноз без заверения: статус HOLD ...
                        "source": f"law-candidate:{dom}:"  # ... источник "law-candidate:<домен>:<признак>" ...
                                  f"{entry['feature']}",  # продолжение имени источника: признак закона
                        "certified": False}  # ответ не заверен: ... certified = False
            except Exception:  # закон неприменим
                continue  # попробовать следующий
        # 3) по умолчанию HOLD — без закона догадок нет
        if not allow_neural:  # нейронная догадка не разрешена
            return {"byte": None, "status": "HOLD",  # без ответа: byte = None, HOLD ...
                    "source": "no-law", "certified": False}  # ... источник no-law, не заверено
        dev = self.model.device  # устройство модели
        ctx_list = list(context)[-self.model.k:]  # последние k байтов от СТАРОГО к НОВОМУ, как в _windows и train_guarded (раньше был обратный порядок — модель получала перевёрнутое окно)
        x = _t.as_tensor([ctx_list], dtype=_t.long, device=dev)  # тензор формы (1, k)
        with self._DomainScope(self, prefer_domain):  # с адаптером домена, если он проходит гейт
            routed = self._route_fiber(context) if prefer_domain is None else None  # волокно без метки домена (Mirror-Hedge по потерям на контексте)
            if routed is not None: self.model.active_fiber = routed  # поставить выбранное волокно
            b = int(self.model.logits(x)[0].argmax())  # b = argmax логитов (байт с максимальным логитом)
            used = self.model.domain_adapter is not None  # применялся ли адаптер
        return {"byte": b, "status": "NEURAL_GUESS", "adapter": used,  # нейронная догадка: байт, применялся ли адаптер ...
                "source": "neural", "certified": False}  # ... источник neural, не заверено
