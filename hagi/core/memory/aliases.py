def _bit_not8(x: int) -> int:
    """Побитовое отрицание по младшим 8 битам: ¬x & 255.

        x: целое число. Возврат — число от 0 до 255."""
    return (~int(x)) & 0xFF  # ¬x, оставленное по маске 0xFF (младшие 8 бит)


def _bit_nand8(x: int, y: int) -> int:
    """Штрих Шеффера по младшим 8 битам: ¬(x & y) & 255.

        x, y: целые числа. Возврат — число от 0 до 255."""
    return (~(int(x) & int(y))) & 0xFF  # ¬(x ∧ y), маска 0xFF


def _bit_nor8(x: int, y: int) -> int:
    """Стрелка Пирса по младшим 8 битам: ¬(x | y) & 255.

        x, y: целые числа. Возврат — число от 0 до 255."""
    return (~(int(x) | int(y))) & 0xFF  # ¬(x ∨ y), маска 0xFF


def _bit_xnor8(x: int, y: int) -> int:
    """Равнозначность по младшим 8 битам: ¬(x ^ y) & 255.

        x, y: целые числа. Возврат — число от 0 до 255."""
    return (~(int(x) ^ int(y))) & 0xFF  # ¬(x ⊕ y), маска 0xFF


def _sign(x: int) -> int:
    """Знак числа: 1, если x > 0; −1, если x < 0; 0 при x = 0.

        x: целое число."""
    return (int(x) > 0) - (int(x) < 0)  # знак sign = [x > 0] − [x < 0]


def _pow_int(x: int, y: int) -> int:
    """Целая степень x^y для показателя y из отрезка 0..8.

        x: основание, y: показатель. Вне отрезка 0..8 — ошибка ValueError."""
    y = int(y)  # показатель в целое число
    if y < 0 or y > 8:  # показатель вне 0..8
        raise ValueError("exponent outside certified range")  # ошибка: показатель вне сертифицированного диапазона
    return int(x) ** y  # степень x^y


