def gamma_bits(n: int) -> int:
    """Число бит гамма-кода Элиаса для положительного целого n: 2·(⌊log2 n⌋) + 1.

        n: положительное целое. Старший значащий бит кодируется единицей, перед ним
        стоят ⌊log2 n⌋ нулей, после — ⌊log2 n⌋ младших бит числа."""
    n = int(n)  # привести к целому
    if n < 1:  # число не положительное
        raise ValueError("gamma_bits expects positive integer")  # ошибка: ожидается положительное целое
    return 2 * (n.bit_length() - 1) + 1  # 2·(длина_двоичной_записи − 1) + 1 = 2·⌊log2 n⌋ + 1


def zigzag(n: int) -> int:
    """Зигзаг-код целого числа в неотрицательное: 2n при n ≥ 0, −2n − 1 при n < 0.

        n: целое число. Возврат — неотрицательное целое."""
    n = int(n)  # привести к целому
    return 2 * n if n >= 0 else -2 * n - 1  # 2n, если n ≥ 0; иначе −2n − 1

