def pack_venn_16_flat() -> bytes:
    """Упаковать 16 масок по 4 бита в 13 байт.

        Биты читаются в порядке (маска, номер бита), дополняются нулями до
        кратности 5; каждые 5 бит сворачиваются в один байт: b = Σ_{i=0..4} t_i·3^(4−i).
        64 бита → 13 групп по 5 (последняя с тремя нулями) → 13 байт."""
    trits = []  # список бит всех масок
    for mask in range(16):  # по маскам 0..15
        for idx in range(4):  # по битам маски
            trits.append((mask >> idx) & 1)  # добавить бит idx маски
    while len(trits) % 5 != 0:  # длина не кратна 5
        trits.append(0)  # добавить нулевой бит
    out = bytearray()  # выходные байты
    for off in range(0, len(trits), 5):  # по группам по 5 бит
        b = 0  # значение байта
        for t in trits[off : off + 5]:  # по битам группы
            b = b * 3 + t  # b = b·3 + t — запись в базисе 3
        out.append(b)  # добавить байт
    assert len(out) == 13  # должно получиться ровно 13 байт
    return bytes(out)  # вернуть байты




def anf_transform(truth_table: Sequence[int]) -> list[int]:
    """Точное преобразование таблицы истинности в полином Жегалкина («бабочка»), O(n·2^n).

        truth_table: 2^k значений 0 или 1. Возврат — коэффициенты полинома:
        f(x) = ⊕_s c_s·Π_{i: бит s_i = 1} x_i. На каждом шаге при ширине step:
        c[i + step + j] ^= c[i + j] для i кратного 2·step и j < step."""
    n_tot = len(truth_table)  # длина таблицы — степень двойки
    if n_tot == 0 or (n_tot & (n_tot - 1)) != 0:  # длина ноль или не степень двойки
        raise ValueError("truth_table length must be a power of 2")  # ошибка
    coeffs = [int(v) & 1 for v in truth_table]  # коэффициенты — копия таблицы по модулю 2
    step = 1  # начальная ширина бабочки
    while step < n_tot:  # пока ширина меньше длины
        for i in range(0, n_tot, step * 2):  # по началам блоков шириной 2·step
            for j in range(step):  # по смещениям внутри первой половины блока
                coeffs[i + step + j] ^= coeffs[i + j]  # сумма c[i + step + j] = c[i + step + j] ⊕ c[i + j]
        step <<= 1  # ширина × 2
    return coeffs  # коэффициенты полинома




def anf_to_call_dag(coeffs: Sequence[int], n_vars: int) -> CallDagExpr:
    """Собрать полином Жегалкина в символьное выражение.

        coeffs: коэффициенты полинома, n_vars: число переменных. sparse — список
        мономов (s, 1) с c_s = 1. Пустой список → константа 0; единственный моном
        s = 0 → константа 1; не более 4 мономов → XOR мономов, моном s ≠ 0 —
        произведение AND переменных битов s; иначе — узел "anf" с параметрами
        (n_vars, sparse)."""
    sparse = tuple((s, 1) for s, c in enumerate(coeffs) if c)  # мономы с единичным коэффициентом
    if len(sparse) == 0:  # мономов нет
        return CallDagExpr.const(0)  # константа 0
    if len(sparse) == 1 and sparse[0][0] == 0:  # единственный моном — свободный член
        return CallDagExpr.const(1)  # константа 1
    if len(sparse) <= 4:  # мономов не больше четырёх
        mons = []  # выражения мономов
        for s, _ in sparse:  # по мономам
            if s == 0:  # свободный член
                mons.append(CallDagExpr.const(1))  # моном — константа 1
            else:  # моном содержит переменные
                vs = [  # переменные монома
                    CallDagExpr.var(i) for i in range(n_vars) if (s >> (n_vars - 1 - i)) & 1  # переменная i, если бит i в s равен 1
                ]  # конец списка
                t = vs[0]  # произведение начинается с первой переменной
                for v in vs[1:]:  # по остальным переменным
                    t = CallDagExpr("bit_and", (t, v))  # произведение t = t ∧ v
                mons.append(t)  # добавить моном
        res = mons[0]  # сумма начинается с первого монома
        for m in mons[1:]:  # по остальным мономам
            res = CallDagExpr("bit_xor", (res, m))  # сумма res = res ⊕ m
        return res  # выражение XOR мономов
    return CallDagExpr("anf", (), (n_vars, sparse))  # узел полинома с числом переменных и списком мономов

