"""Голова функций Венна, упаковка масок и преобразование в алгебраическую нормальную форму.

Части файла:
  * голова Венна: два входа x1, x2 ∈ {0, 1} переходят в s = 2x − 1 ∈ {−1, +1};
    четыре нейрона с выпрямлением дают атомы
    max(0, (−s1 − s2)/2), max(0, (−s1 + s2)/2), max(0, (s1 − s2)/2), max(0, (s1 + s2)/2);
    ровно один атом равен 1; маска из 4 бит задаёт любую булеву функцию двух
    аргументов: выход = round(атомы · w), w_j = бит j маски;
  * упаковка 16 масок: 64 бита в базисе 3 по 5 бит на байт → 13 байт;
  * преобразование Жегалкина (алгебраальная нормальная форма) «бабочкой»:
    на каждом шаге step коэффициент c[i + step + j] ^= c[i + j], step = 1, 2, 4, …;
  * извлечение переменных, входящих в полином, и сборка выражения CallDagExpr:
    XOR не более четырёх мономов через bit_and / bit_xor, иначе операция "anf".
"""

