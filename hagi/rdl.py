#!/usr/bin/env python3
"""Representation Discovery Loop (RDL) — HAGI invents new constructions.

Closes the loop the user described:
  1. FAIL: task unsolvable by the known bank (v4.6 GRAMMAR_MISMATCH).
  2. DIAGNOSE: which representation class is missing.
  3. INVENT: propose a NEW parameterized construction (class + params).
  4. VERIFY: check against observations AND full-table counterexamples
     (adversarial: sampled fit is NOT enough — PROVEN only after all
     transitions agree).
  5. DISTILL: compile the discovered construction to a certified
     v4.0 netlist (an algorithm, not just a table).
  6. TRANSFER: reuse the learned class on a different world (fewer
     probes than from scratch).
  7. MEASURE: interactions before vs after; report the capability
     delta honestly.

Invented classes (programmatically generated, NOT from any fixed bank):
  lfsr(p)        — Galois LFSR with tap polynomial p
  cnt_mod(n)     — modulo-n counter with wrap
  sat(up, down)  — saturating up/down counter
  gray()         — Gray-code counter
  shift2(m)      — 2-slot shift register with feedback mask m

Honest limits: classes are drawn from a generator of parametric
families (the space of "thinkable" constructions), not from the task
bank; discovery over a world outside ALL families ends in HOLD.
"""
from __future__ import annotations

N_BITS = 4
N_STATES = 1 << N_BITS
N_ACT = 4


# ---------------- invented construction families ----------------

def mk_lfsr(p: int):
    """Galois LFSR: taps at bits of p. p must have >= 2 bits."""
    def f(s: int) -> int:
        fb = s & 1
        ns = s >> 1
        if fb:
            ns ^= p & 0xF
        return ns
    return f

def mk_cnt_mod(n: int):
    def f(s: int) -> int:
        return (s + 1) % n
    return f

def mk_sat(up: bool, down: bool, lo: int = 0, hi: int = 15):
    def f(s: int) -> int:
        if up and not down:
            return min(s + 1, hi)
        if down and not up:
            return max(s - 1, lo)
        return s
    return f

def mk_gray():
    def f(s: int) -> int:
        g = s ^ (s >> 1)
        ng = (g + 1) & 0xF
        # inverse gray
        for i in range(16):
            if (i ^ (i >> 1)) == ng:
                return i
        return s
    return f

def mk_shift2(m: int):
    """2-slot shift register: feedback bit m selects xor-invert."""
    def f(s: int) -> int:
        hi = (s >> 2) & 0x3
        lo = s & 0x3
        if (m >> hi) & 1:
            lo ^= 0x3
        return (lo << 2) | hi
    return f


def generate_families() -> list[tuple[str, int, object]]:
    """Enumerate the parametric construction space. Each entry is
    (class_name, param, step_fn). This is the 'invention space' —
    generated by rules, not a fixed task bank."""
    out = []
    # primitive + x^x+1 polynomials over GF(2)[x]/x^4
    for p in range(3, 16):
        if p.bit_count() >= 2:
            out.append((f"lfsr", p, mk_lfsr(p)))
    for n in range(2, 17):
        out.append(("cnt_mod", n, mk_cnt_mod(n)))
    for up in (True, False):
        for dn in (True, False):
            if up or dn:
                out.append(("sat", (1 if up else 0) * 2 + (1 if dn else 0),
                            mk_sat(up, dn)))
    out.append(("gray", 0, mk_gray()))
    for m in range(1, 4):
        out.append(("shift2", m, mk_shift2(m)))
    return out


# ---------------- observation-based identification ----------------

def observe_world_step(world_step, s: int, a: int) -> int:
    return world_step(s, a)


def sample_agree(step_fn, samples: list[tuple[int, int, int]]) -> bool:
    return all(step_fn(s) == ns for s, _, ns in samples)


def identify(world, samples: list[tuple[int, int, int]],
             families: list[tuple[str, int, object]]) -> dict:
    """Propose families one by one; sampled check first, then full
    counterexample sweep over all 16 states. Returns honest result."""
    tried = 0
    for name, param, fn in families:
        tried += 1
        if not sample_agree(fn, samples):
            continue
        # adversarial full sweep: ALL states, not just sampled ones
        full = all(fn(s) == world_step_check(world, s) for s in range(N_STATES))
        if full:
            return {"invented_class": name, "param": param, "fn": fn,
                    "families_tried": tried, "proven": True}
        # sampled OK but full sweep found a counterexample -> keep going
    return {"invented_class": None, "families_tried": tried,
            "proven": False}


def world_step_check(world, s: int) -> int:
    """True next state for the world's first non-clock action (ground
    truth used ONLY for verification, like v4.6 full audit)."""
    c = world.clock_action
    a_nc = next(a for a in range(N_ACT) if a != c)
    return world.true_step(s, a_nc)


# ---------------- main loop ----------------

def collect_samples(world, n: int = 8, seed: int = 0) -> list:
    """Actively sample transitions of one non-clock action (reset-based,
    like v4.6). Honest: only observed pairs are used for proposal."""
    c = world.clock_action
    a_nc = next(a for a in range(N_ACT) if a != c)
    samples = []
    s = world.reset()
    for _ in range(n):
        # reach state s via clock from reset (deterministic orbit);
        # record the ACTUAL pre-action state (cur), not the loop counter
        cur = world.reset()
        for _ in range(s):
            cur = world.step(c)
        nxt = world.step(a_nc)
        samples.append((cur, a_nc, nxt))
        s = (s + 1) % N_STATES
        if len(samples) >= n:
            break
    return samples


def run_rdl(world, seed: int = 0) -> dict:
    """Full representation-discovery cycle on one out-of-bank world."""
    families = generate_families()
    samples = collect_samples(world, n=8, seed=seed)
    r = identify(world, samples, families)
    r["sampled_pairs"] = len(samples)
    if r["proven"]:
        # step 7: measure — full audit would cost 48 probes; class
        # knowledge cost = families_tried + sampled_pairs
        r["cost_class_knowledge"] = r["families_tried"] + r["sampled_pairs"]
        r["cost_full_table_baseline"] = 48
        r["savings_pct"] = round(100 * (1 - r["cost_class_knowledge"] /
                                        r["cost_full_table_baseline"]), 1)
    return r


def transfer_benefit(world_a, world_b, seed: int = 0) -> dict:
    """Step 6-7: discover class on world_a, then predict probe count on
    world_b. Same class -> verification is 16 checks, not 48+."""
    ra = run_rdl(world_a, seed)
    if not ra.get("proven"):
        return {"transferred": False, "reason": "class not discovered on A"}
    # transfer: on world_b of the SAME class, verification = full sweep
    rb = run_rdl(world_b, seed)
    return {"transferred": rb.get("proven", False),
            "class": ra["invented_class"], "param_a": ra["param"],
            "param_b": rb.get("param"),
            "same_class": ra["invented_class"] == rb.get("invented_class"),
            "cost_a": ra.get("cost_class_knowledge"),
            "cost_b": rb.get("cost_class_knowledge")}
