#!/usr/bin/env python3
"""Literacy corpus: teach HAGI to READ code, from boolean algebra up.

WAVE 181 REWRITE: every fact in the corpus is PRINTED FROM REAL
COMPUTATION — no hand-written truth tables, no manual hex dumps.
If a line says "6 & 3 = 2", it is `print(f"{a} & {b} = {a & b}")`.
Manual text is limited to section headers and task framing; all
checkable content is machine-generated.

Layers:
  0  boolean algebra: truth tables (generated)
  1  bytes <-> ASCII <-> hex (generated from encode())
  2  Python bitwise ops on numbers (generated)
  3  code -> byte stream (generated from encode())
  4  execution traces of tiny functions (generated by running them)
  5  real HAGI module signatures (generated from inspect/ast)
  6  Lean token stream (generated from encode())
"""
import ast
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "training" / "literacy"
OUT = OUT_DIR / "bits_corpus.txt"


def layer0_boolean(rows):
    rows.append("L0 BOOLEAN ALGEBRA (generated)")
    # NOT / AND / OR / XOR over 4-bit words — printed from real ops
    for x in range(16):
        rows.append(f"NOT {x:04b} = {~x & 0xF:04b}")
    for x in range(16):
        for y in range(16):
            rows.append(f"{x:04b} AND {y:04b} = {x & y:04b}")
            rows.append(f"{x:04b} XOR {y:04b} = {x ^ y:04b}")
            rows.append(f"{x:04b} OR  {y:04b} = {x | y:04b}")
    # single-bit identities, printed from checks
    facts = [
        ("XOR self-inverse", all((a ^ a) == 0 for a in range(2))),
        ("XOR commutes", all((a ^ b) == (b ^ a) for a in range(2) for b in range(2))),
        ("AND absorbs", all((a & 0) == 0 for a in range(2))),
        ("OR identity", all((a | 0) == a for a in range(2))),
        ("DeMorgan NOT(a AND b) = NOT a OR NOT b",
         all((not (a and b)) == ((not a) or (not b))
             for a in (0, 1) for b in (0, 1))),
    ]
    for name, ok in facts:
        rows.append(f"CHECK {name} -> {'TRUE' if ok else 'FAIL'}")


def layer1_bytes(rows):
    rows.append("L1 BYTES ASCII HEX (generated)")
    # printable ASCII, straight from ord()
    for b in range(0x20, 0x7F):
        c = chr(b)
        rows.append(f"CHR {b:3d} HEX {b:02x} BIN {b:08b} = '{c}'")
    # words encoded, printed from encode()
    for w in ["def", "class", "return", "import", "if", "for",
              "theorem", "proof", "rfl", "hagi", "xor", "and", "or"]:
        bs = w.encode("ascii")
        rows.append(f"WORD '{w}' = " + " ".join(f"{b:02x}" for b in bs))


def layer2_python_ops(rows):
    rows.append("L2 PYTHON BITWISE OPS (generated)")
    for a in range(0, 64, 3):
        for b in (1, 3, 5, 7, 10, 12):
            rows.append(f"{a} AND {b} = {a & b}")
            rows.append(f"{a} XOR {b} = {a ^ b}")
            rows.append(f"{a} OR {b} = {a | b}")
        rows.append(f"{a} SHL1 = {(a << 1) & 0xFF}")
        rows.append(f"{a} SHR1 = {a >> 1}")
        rows.append(f"{a} MOD7 = {a % 7}")
        rows.append(f"{a} POPCOUNT = {bin(a).count('1')}")


def layer3_code_bytes(rows):
    rows.append("L3 CODE AS BYTES (generated from encode)")
    snippets = [
        "def f(x):",
        "    return x & 5",
        "    return x ^ 3",
        "def g(a, b):",
        "    return (a ^ b) & 0xFF",
        "class H:",
        "    def __init__(self):",
        "        self.k = 16",
        "for i in range(8):",
        "    r = r ^ i",
        "if x > 0:",
        "    return x",
    ]
    for s in snippets:
        rows.append("CODE " + s)
        rows.append("HEX " + " ".join(f"{b:02x}" for b in s.encode("ascii")))


def layer4_execution(rows):
    rows.append("L4 EXECUTION TRACES (generated by running the fns)")
    # f: x & 5
    f = lambda x: x & 5
    rows.append("FN f(x) = x AND 5")
    for x in range(0, 32, 3):
        rows.append(f"CALL f({x}) -> {f(x)}")
    # g: (a ^ b) & 0xFF
    g = lambda a, b: (a ^ b) & 0xFF
    rows.append("FN g(a, b) = (a XOR b) AND 255")
    for a in range(0, 32, 5):
        for b in (1, 4, 9):
            rows.append(f"CALL g({a}, {b}) -> {g(a, b)}")
    # loop trace: r starts 0, r ^= i for i in 0..7 — printed per step
    rows.append("FN loop8: r=0; for i in 0..7: r ^= i")
    r = 0
    for i in range(8):
        r ^= i
        rows.append(f"  i={i} r={r}")
    # parity via popcount
    rows.append("FN parity(x) = popcount(x) mod 2")
    for x in range(0, 16):
        rows.append(f"CALL parity({x}) -> {bin(x).count('1') % 2}")


def layer5_hagi_signatures(rows):
    rows.append("L5 REAL HAGI MODULE SIGNATURES (generated from ast)")
    mods = ["cegis.py", "representations.py", "diagnosis.py",
            "unified.py", "reifier.py", "invention.py", "lm.py",
            "core.py"]
    for m in mods:
        p = ROOT / "hagi" / m
        if not p.exists():
            continue
        tree = ast.parse(p.read_text(encoding="utf-8"))
        defs = []
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                args = ""
                if isinstance(node, ast.FunctionDef):
                    try:
                        args = ast.unparse(node.args)
                    except Exception:
                        args = "..."
                defs.append(f"{'class' if isinstance(node, ast.ClassDef) else 'def'} "
                            f"{node.name}({args if isinstance(node, ast.FunctionDef) else ''})")
        rows.append(f"MODULE hagi/{m}: {len(defs)} defs")
        for d in defs[:40]:
            rows.append("  " + d)


def layer6_lean_tokens(rows):
    rows.append("L6 LEAN TOKENS AS BYTES (generated from encode)")
    for tok in ["theorem", "proof", "rfl", "exact", "simp", "rw",
                "induction", ":=", "->", "∀", "λ", "Nat", "Bool"]:
        tb = tok.encode("utf-8")
        rows.append("TOK " + " ".join(f"{b:02x}" for b in tb) + " = " + tok)
    # real theory names from primes
    theory = Path("C:/primes/Hagi/Theory")
    if theory.exists():
        names = sorted(p.stem for p in theory.glob("*.lean"))[:30]
        rows.append(f"THEORY FILES: {len(names)} shown")
        for n in names:
            rows.append("  " + n)


def main():
    rows = ["HAGI LITERACY CORPUS — ALL FACTS MACHINE-GENERATED"]
    layer0_boolean(rows)
    layer1_bytes(rows)
    layer2_python_ops(rows)
    layer3_code_bytes(rows)
    layer4_execution(rows)
    layer5_hagi_signatures(rows)
    layer6_lean_tokens(rows)
    rng = random.Random(7)
    # light shuffle preserving locality? keep order (curriculum):
    # L0 first, later layers build on it. No shuffle.
    text = "\n".join(rows) + "\n"
    OUT.write_bytes(text.encode("utf-8"))
    print(f"{OUT}: {len(text.encode('utf-8'))} bytes, {len(rows)} rows")
    # self-verify: every 'A OP B = C' line must be true
    bad = 0
    for line in rows:
        parts = line.split()
        if len(parts) == 5 and parts[3] == "=" and parts[1] in ("AND", "XOR", "OR"):
            a, op, b, _, c = parts
            try:
                av, bv, cv = int(a, 2), int(b, 2), int(c, 2)
                want = {"AND": av & bv, "XOR": av ^ bv, "OR": av | bv}[op]
                if want != cv:
                    print("WRONG:", line)
                    bad += 1
            except ValueError:
                pass
        elif len(parts) == 5 and parts[1] in ("AND", "XOR", "OR") and parts[3] == "=":
            a, op, b, _, c = parts
            try:
                av, bv, cv = int(a), int(b), int(c)
                want = {"AND": av & bv, "XOR": av ^ bv, "OR": av | bv}[op]
                if want != cv:
                    print("WRONG:", line)
                    bad += 1
            except ValueError:
                pass
    print(f"self-verify: {'ALL TRUE' if bad == 0 else f'{bad} WRONG LINES'}")


if __name__ == "__main__":
    main()
